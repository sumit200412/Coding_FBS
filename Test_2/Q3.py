radius = 20
length = 50
breadth = 40
cost = 35
time = 5
pi = 3.14

perimeter = length + length + breadth + (pi * radius)

total_fencing = perimeter * time

total_cost = total_fencing * cost

print(f"Perimeter of field = {perimeter} m")
print(f"Total fencing = {total_fencing} m")
print(f"Total cost = {total_cost}Rs.")